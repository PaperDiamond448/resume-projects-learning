def _norm(s: str) -> str:
    return (s or "").strip().lower()


def find_guide(app: str) -> dict | None:
    """口语 App 名 → 攻略(dict) 或 None。按 key 或 aliases 模糊匹配。"""
    q = _norm(app)
    if not q:
        return None
    for key, g in APP_GUIDES.items():
        if q == _norm(key):
            return g
        for a in g["aliases"]:
            na = _norm(a)
            if na and (na in q or q in na):
                return g
    return None


def hints_for(app: str) -> str:
    g = find_guide(app)
    return g["hints"] if g else ""


def recipe_for(app: str, goal: str) -> list[str] | None:
    """App + 任务 → 命中的手写步骤列表 或 None（要求 recipe 的所有关键词都在 goal 里）。"""
    g = find_guide(app)
    if not g:
        return None
    gl = goal or ""
    for kws, steps in g.get("recipes", {}).items():
        if all(k in gl for k in kws):
            return list(steps)
    return None
